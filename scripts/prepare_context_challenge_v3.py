def unmark(marked: str) -> tuple[str, list[list]]:
    parts: list[str] = []
    entities: list[list] = []
    cursor = length = 0
    for match in MARKER.finditer(marked):
        prefix = marked[cursor:match.start()]
        parts.append(prefix)
        length += len(prefix)
        label, value = match.groups()
        entities.append([label, length, length + len(value)])
        parts.append(value)
        length += len(value)
        cursor = match.end()
    parts.append(marked[cursor:])
    text = "".join(parts)
    if "[[" in text or "]]" in text:
        raise ValueError(f"Некорректная ручная метка: {marked!r}")
    return text, entities


def build_cases() -> list[dict]:
    records = []
    for category, examples in SOURCE_CASES.items():
        for index, marked in enumerate(examples, 1):
            text, entities = unmark(marked)
            record = {
                "id": f"context-v3/{category}/{index:03d}",
                "source": "manual_context_challenge_v3",
                "category": category,
                "scope": "core" if category in {"compound_surnames", "compound_declension", "quoted_people", "human_lev"} else "semantic",
                "note": "Эталон вручную задан в исходнике до запуска; название организации/товара не обозначает человека, а цитата о человеке содержит ПДн.",
                "text": text,
                "entities": entities,
            }
            to_bio(text, entities_of(record))
            records.append(record)
    if len({record["text"] for record in records}) != len(records):
        raise ValueError("Повтор текста в контрольном наборе")
    return records


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=PROJECT_ROOT / "data" / "context-v3")
    args = parser.parse_args()
    if args.output_dir.exists():
        raise FileExistsError("Контрольный набор уже зафиксирован; выберите другой --output-dir для проверки воспроизводимости")
    records = build_cases()
    write_jsonl(args.output_dir / "cases.jsonl", records)
    digest = hashlib.sha256((args.output_dir / "cases.jsonl").read_bytes()).hexdigest()
    write_json(args.output_dir / "manifest.json", {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "texts": len(records),
        "categories": dict(Counter(record["category"] for record in records)),
        "cases_sha256": digest,
        "annotation": "Manually authored positive spans in SOURCE_CASES; no model or predictions are read.",
        "purpose": "Prospective regression challenge fixed before v3 contextual corrections; never training or validation for epoch selection.",
        "semantic_policy": [
            "Names of companies, brands, product models, files and variables explicitly denote non-person referents and have no name-component labels.",
            "References to real people in ordinary or nested quotations remain positive, including authors of books and quotations.",
            "Lion as an explicitly described animal is negative; a person named Lev is positive, including declined forms.",
            "Whole hyphenated surname is one SURNAME; initials include their abbreviation period.",
        ],
        "limitations": [
            "176 hand-written adversarial texts emphasize selected phenomena; not a representative random sample of Russian documents.",
            "Unqualified strings such as Lev or Ivanov with no referent context are omitted as ambiguous.",
            "No statistical independence is claimed for shared name vocabulary or contextual constructions; texts must remain frozen after inspection.",
        ],
    })
    print(f"Prepared {len(records)} texts; SHA256={digest}", flush=True)


if __name__ == "__main__":
    main()
